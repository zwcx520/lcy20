// 用于跟踪已显示的问候语
let usedGreetings = [];

// 弹窗容器
const popupContainer = document.getElementById('popup-container');

// 弹窗生成间隔
let popupInterval;
// 爱心生成间隔
let heartInterval;

// 自动开始生成弹窗
window.addEventListener('load', function() {
    // 生成背景爱心
    createHearts();
    
    // 进一步加快弹窗速度，每0.1秒生成一个弹窗
    popupInterval = setInterval(createPopup, 100);
});

// 创建弹窗
function createPopup() {
    const popup = document.createElement('div');
    popup.className = 'popup';
    
    // 过滤出未使用的问候语
    let availableGreetings = greetings.filter(greeting => !usedGreetings.includes(greeting));
    
    // 如果所有问候语都已使用，则重置
    if (availableGreetings.length === 0) {
        usedGreetings = [];
        availableGreetings = [...greetings];
    }
    
    // 从可用问候语中随机选择一个
    const randomIndex = Math.floor(Math.random() * availableGreetings.length);
    const selectedGreeting = availableGreetings[randomIndex];
    
    // 将选择的问候语添加到已使用列表
    usedGreetings.push(selectedGreeting);
    
    popup.innerHTML = `<p>${selectedGreeting}</p>`;
    
    // 先添加到容器，以便获取实际尺寸
    popupContainer.appendChild(popup);
    
    // 获取弹窗尺寸
    const popupWidth = popup.offsetWidth;
    const popupHeight = popup.offsetHeight;
    
    // 计算随机位置，确保弹窗完全在屏幕内
    const maxX = window.innerWidth - popupWidth;
    const maxY = window.innerHeight - popupHeight;
    const randomX = Math.random() * maxX;
    const randomY = Math.random() * maxY;
    
    popup.style.left = `${randomX}px`;
    popup.style.top = `${randomY}px`;
    
    // 随机颜色边框
    const colors = ['#e91e63', '#9c27b0', '#3f51b5', '#2196f3', '#00bcd4', '#4caf50'];
    const randomColor = colors[Math.floor(Math.random() * colors.length)];
    popup.style.borderLeft = `4px solid ${randomColor}`;
    
    // 3秒后移除弹窗
    setTimeout(() => {
        popup.classList.add('fade-out');
        setTimeout(() => {
            popup.remove();
        }, 500);
    }, 3000);
}

// 创建背景爱心
function createHearts() {
    heartInterval = setInterval(() => {
        const heart = document.createElement('div');
        heart.className = 'heart';
        
        // 随机位置
        const randomX = Math.random() * window.innerWidth;
        heart.style.left = `${randomX}px`;
        
        // 随机大小
        const randomSize = Math.random() * 10 + 10;
        heart.style.width = `${randomSize}px`;
        heart.style.height = `${randomSize}px`;
        
        // 随机飘落速度
        const randomDuration = Math.random() * 10 + 10;
        heart.style.animationDuration = `${randomDuration}s`;
        
        // 随机延迟
        const randomDelay = Math.random() * 5;
        heart.style.animationDelay = `${randomDelay}s`;
        
        // 添加到页面
        document.body.appendChild(heart);
        
        // 动画结束后移除
        setTimeout(() => {
            heart.remove();
        }, (randomDuration + randomDelay) * 1000);
    }, 500);
}

// 页面加载时添加背景效果
window.addEventListener('load', function() {
    // 创建背景效果容器
    const backgroundEffect = document.createElement('div');
    backgroundEffect.className = 'background-effect';
    document.body.appendChild(backgroundEffect);
    
    // 页面加载动画
    document.body.style.opacity = '0';
    document.body.style.transition = 'opacity 0.8s ease';
    setTimeout(() => {
        document.body.style.opacity = '1';
    }, 300);
});